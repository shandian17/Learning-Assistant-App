  const saved = localStorage.getItem(storageKey);
  const browserLanguage = navigator.languages?.[0] || navigator.language || 'en';
  const detected = browserLanguage.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  const language = saved === 'en' || saved === 'zh-CN' ? saved : detected;

  function t(source, values = {}) {
    const template = language === 'en' ? (translations[source] || source) : source;
    return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
  }

  function translateTextNode(node) {
    const source = node.nodeValue;
    const trimmed = source.trim();
    if (!trimmed || !Object.hasOwn(translations, trimmed)) return;
    node.nodeValue = source.replace(trimmed, translations[trimmed]);
  }

  function apply(root = document) {
    document.documentElement.lang = language;
    if (language !== 'en') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.parentElement?.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
    root.querySelectorAll?.('[aria-label], [title], [placeholder]').forEach(element => {
      for (const attribute of ['aria-label', 'title', 'placeholder']) {
        const value = element.getAttribute(attribute);
        if (value && Object.hasOwn(translations, value)) element.setAttribute(attribute, translations[value]);
      }
    });
  }

  function setLanguage(value) {
    if (!['zh-CN', 'en'].includes(value) || value === language) return;
    localStorage.setItem(storageKey, value);
    location.reload();
  }

  function message(value, fallback) {
    if (!value) return t(fallback);
    return language === 'en' && /[\u3400-\u9fff]/.test(value) ? t(fallback) : value;
  }

  apply(document);
  const toggle = document.getElementById('language-toggle');
  if (toggle) {
    toggle.dataset.language = language;
    toggle.setAttribute('aria-label', language === 'en' ? '切换到中文' : 'Switch to English');
    toggle.setAttribute('title', language === 'en' ? '切换到中文' : 'Switch to English');
    toggle.addEventListener('click', () => setLanguage(language === 'en' ? 'zh-CN' : 'en'));
  }

  return {
    language,
    locale: language === 'en' ? 'en-US' : 'zh-CN',
    t,
    message,
    apply,
    setLanguage
  };
